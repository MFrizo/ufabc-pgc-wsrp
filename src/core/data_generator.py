"""
Module: data_generator
Description: Single point of generation of synthetic, reproducible instances for every
             WSRP model. Each call builds the full instance (graph, time parameters,
             time windows) and every model reads only the keys it needs.
             Each feature draws from its own random stream derived from the seed, so
             adding a feature never changes the data generated by the previous ones.
"""

import math
import numpy as np
from typing import Any, Optional

# Random stream of each feature. The graph uses the plain seed; every other feature
# uses default_rng([random_seed, stream]), so its draws never shift the graph's.
TIME_WINDOWS_STREAM = 1
ASSIGNMENTS_STREAM = 2
SERVICE_TIMES_STREAM = 3
HOMES_STREAM = 4


def generate_wsrp_instance(num_properties: int = 5, random_seed: int = 42, num_brokers: int = 1,
                           travel_time: int = 30, service_time: int = 60, horizon: int = 600,
                           fixed_ratio: float = 0.2, window_width: tuple[int, int] = (120, 360),
                           assigned_ratio: float = 0.4, service_time_variation: int = 0,
                           speed_profile: Optional[list[tuple[int, float]]] = None,
                           working_hours: tuple[int, int] = (0, 540),
                           start_at_homes: bool = False) -> dict[str, Any]:
    """
    Generates a synthetic WSRP instance with the data of every model.

    Args:
        num_properties (int): The number of properties to be visited.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        num_brokers (int): Number of brokers |K|. The hidden schedule behind the time windows
            is split among them, so with more than one broker the visits may overlap.
        travel_time (int): Constant travel time T between any two nodes, in minutes.
        service_time (int): Constant visit duration S, in minutes.
        horizon (int): Target length of the working day over which the visits are spread, in
            minutes (e.g. 600 = 08:00 to 18:00). Extended when the visits don't fit in it.
        fixed_ratio (float): Share of the properties with a fixed start time.
        window_width (tuple[int, int]): Min and max width of a flexible time window, in minutes.
        assigned_ratio (float): Share of the properties whose visit already has a broker.
        service_time_variation (int): Each visit lasts a duration drawn from
            [S - variation, S + variation], in minutes. With 0, every visit lasts S.
        speed_profile (Optional[list[tuple[int, float]]]): Periods of the day as (start minute,
            speed in distance units per minute), the first starting at 0. The travel time of a
            trip depends on the period it leaves in. With None, every trip takes T.
        working_hours (tuple[int, int]): Start and regular end of every broker's working day,
            in minutes (e.g. (0, 540) = 08:00 to 17:00).
        start_at_homes (bool): Whether each broker of the hidden schedule leaves his own home
            instead of the agency, for the models where the brokers start the day at home.

    Returns:
        dict[str, Any]: The instance payload. Keys and the models that read them:
            - 'num_nodes', 'coordinates', 'distance_matrix': all models.
            - 'travel_time': M1 to M4.
            - 'service_time': M1 to M3.
            - 'earliest_start', 'latest_start', 'fixed_visits': M1 onwards.
            - 'num_brokers': M2 onwards.
            - 'assigned_broker': M3 onwards.
            - 'service_times': M4 onwards.
            - 'period_starts', 'travel_times': M5 onwards.
            - 'home_coordinates', 'home_distances', 'home_travel_times': M7 onwards.
            - 'shift_start', 'shift_end': M7.
    """
    num_nodes = num_properties + 1

    data_payload = _generate_graph(num_nodes, random_seed)
    data_payload['service_times'] = _generate_service_times(num_nodes, random_seed, service_time,
                                                            service_time_variation)
    return _complete_instance(data_payload, random_seed=random_seed, num_brokers=num_brokers,
                              travel_time=travel_time, service_time=service_time, horizon=horizon,
                              fixed_ratio=fixed_ratio, window_width=window_width, assigned_ratio=assigned_ratio,
                              speed_profile=speed_profile, working_hours=working_hours,
                              start_at_homes=start_at_homes)


def _complete_instance(data_payload: dict[str, Any], random_seed: int, num_brokers: int, travel_time: int,
                       service_time: int, horizon: int, fixed_ratio: float, window_width: tuple[int, int],
                       assigned_ratio: float, speed_profile: Optional[list[tuple[int, float]]],
                       working_hours: tuple[int, int], start_at_homes: bool) -> dict[str, Any]:
    """
    Fills travel times, homes and a feasible hidden schedule on a graph that already
    has coordinates, a distance matrix and the visit durations.

    Args:
        data_payload (dict[str, Any]): Instance with 'num_nodes', 'coordinates',
            'distance_matrix' and 'service_times' already set.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        num_brokers (int): Number of brokers |K|.
        travel_time (int): Constant travel time T, used when there is no speed profile.
        service_time (int): Constant visit duration S kept for the models that read it.
        horizon (int): Target length of the working day, in minutes.
        fixed_ratio (float): Share of the properties with a fixed start time.
        window_width (tuple[int, int]): Min and max width of a flexible time window, in minutes.
        assigned_ratio (float): Share of the properties whose visit already has a broker.
        speed_profile (Optional[list[tuple[int, float]]]): Periods of the day as (start minute,
            speed in distance units per minute). With None, every trip takes T.
        working_hours (tuple[int, int]): Start and regular end of every broker's working day.
        start_at_homes (bool): Whether each broker of the hidden schedule leaves his own home.

    Returns:
        dict[str, Any]: The same payload, with the keys every model reads filled in.
    """
    num_nodes = data_payload['num_nodes']
    data_payload['num_brokers'] = num_brokers
    data_payload['travel_time'] = travel_time
    data_payload['service_time'] = service_time
    data_payload.update(_generate_travel_times(data_payload['distance_matrix'], travel_time, speed_profile))
    data_payload.update(_generate_homes(random_seed, num_brokers, data_payload['coordinates'], travel_time,
                                        speed_profile))

    # The hidden schedule assumes the slowest period on every trip, so it stays feasible
    # whichever period each trip actually leaves in
    leg_times = np.max(data_payload['travel_times'], axis=0).tolist()
    if start_at_homes:
        first_legs = np.max(data_payload['home_travel_times'], axis=0).tolist()
    else:
        first_legs = [leg_times[0]] * num_brokers

    time_windows = _generate_time_windows(num_nodes, random_seed, num_brokers, leg_times, first_legs,
                                          data_payload['service_times'], horizon, fixed_ratio, window_width)
    reference_broker = time_windows.pop('reference_broker')
    data_payload.update(time_windows)
    data_payload['assigned_broker'] = _generate_assignments(num_nodes, random_seed, reference_broker,
                                                            assigned_ratio)
    data_payload['shift_start'] = [working_hours[0]] * num_brokers
    data_payload['shift_end'] = [working_hours[1]] * num_brokers

    return data_payload


def _generate_graph(num_nodes: int, random_seed: int) -> dict[str, Any]:
    """
    Distributes the nodes in a 100x100 grid map and computes the Euclidean distance matrix.

    Args:
        num_nodes (int): Total number of nodes |V|. Index 0 is the depot.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.

    Returns:
        dict[str, Any]: The number of nodes, coordinates, and the computed distance matrix.
    """
    # 1. Enforcing Reproducibility
    rng = np.random.default_rng(random_seed)

    # 2. Spatial Distribution
    # Generating random (x, y) coordinates in a 100x100 grid map
    # Index 0 will always represent the Depot (Real Estate Agency)
    coordinates = rng.random((num_nodes, 2)) * 100.0

    # 3. Distance Matrix Computation
    # Creating an N x N matrix initialized with zeros
    distance_matrix = np.zeros((num_nodes, num_nodes))

    for i in range(num_nodes):
        for j in range(num_nodes):
            if i != j:
                # Calculating Euclidean distance between node i and node j
                dist = math.hypot(coordinates[i][0] - coordinates[j][0],
                                  coordinates[i][1] - coordinates[j][1])
                # Rounding to 2 decimal places to avoid floating-point representation issues
                distance_matrix[i][j] = round(dist, 2)

    return {
        'num_nodes': num_nodes,
        'coordinates': coordinates.tolist(),
        'distance_matrix': distance_matrix.tolist()
    }


def _generate_service_times(num_nodes: int, random_seed: int, service_time: int,
                            service_time_variation: int) -> list[int]:
    """
    Draws the duration of every visit around the constant visit duration S.

    Args:
        num_nodes (int): Total number of nodes |V|. Index 0 is the depot.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        service_time (int): Mean visit duration S, in minutes.
        service_time_variation (int): Max distance of a duration from S, in minutes.

    Returns:
        list[int]: The duration s_i of the visit at each node, with s_0 = 0 at the depot.
    """
    rng = np.random.default_rng([random_seed, SERVICE_TIMES_STREAM])

    durations = rng.integers(service_time - service_time_variation, service_time + service_time_variation + 1,
                             size=num_nodes - 1)

    return [0] + [int(duration) for duration in durations]


def _generate_travel_times(distance_matrix: list[list[float]], travel_time: int,
                           speed_profile: Optional[list[tuple[int, float]]]) -> dict[str, Any]:
    """
    Computes the travel time of every trip in every period of the day.

    Args:
        distance_matrix (list[list[float]]): Distance c_ij between every pair of nodes.
        travel_time (int): Constant travel time T, used when there is no speed profile.
        speed_profile (Optional[list[tuple[int, float]]]): Periods of the day as (start minute,
            speed in distance units per minute), the first starting at 0.

    Returns:
        dict[str, Any]: The start minute of each period and, for each period, the matrix of
            travel times t_ij in whole minutes (rounded up) of a trip leaving in it.
    """
    num_nodes = len(distance_matrix)

    if speed_profile is None:
        return {
            'period_starts': [0],
            'travel_times': [[[0 if i == j else travel_time for j in range(num_nodes)] for i in range(num_nodes)]]
        }

    return {
        'period_starts': [start for start, _ in speed_profile],
        'travel_times': [[[math.ceil(distance / speed) for distance in row] for row in distance_matrix]
                         for _, speed in speed_profile]
    }


def _generate_homes(random_seed: int, num_brokers: int, coordinates: list[list[float]], travel_time: int,
                    speed_profile: Optional[list[tuple[int, float]]]) -> dict[str, Any]:
    """
    Places the home of every broker in the same 100x100 grid map as the nodes, emulating
    the brokers' own depots, and computes the distance and travel times to every node.

    Args:
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        num_brokers (int): Number of brokers |K|.
        coordinates (list[list[float]]): (x, y) of every node.
        travel_time (int): Constant travel time T, used when there is no speed profile.
        speed_profile (Optional[list[tuple[int, float]]]): Periods of the day as (start minute,
            speed in distance units per minute), the first starting at 0.

    Returns:
        dict[str, Any]: The home coordinates, the distance from each home to each node and,
            for each period, the travel time in whole minutes (rounded up) of that trip.
    """
    rng = np.random.default_rng([random_seed, HOMES_STREAM])
    home_coordinates = rng.random((num_brokers, 2)) * 100.0

    home_distances = [[round(math.hypot(home[0] - node[0], home[1] - node[1]), 2) for node in coordinates]
                      for home in home_coordinates]

    if speed_profile is None:
        home_travel_times = [[[travel_time for _ in row] for row in home_distances]]
    else:
        home_travel_times = [[[math.ceil(distance / speed) for distance in row] for row in home_distances]
                             for _, speed in speed_profile]

    return {
        'home_coordinates': home_coordinates.tolist(),
        'home_distances': home_distances,
        'home_travel_times': home_travel_times
    }


def _generate_time_windows(num_nodes: int, random_seed: int, num_brokers: int, leg_times: list[list[int]],
                           first_legs: list[list[int]], service_times: list[int], horizon: int,
                           fixed_ratio: float, window_width: tuple[int, int]) -> dict[str, Any]:
    """
    Builds the time windows around a hidden reference schedule, which guarantees the
    instance is feasible. A share of the visits gets a fixed start time (e_i = l_i),
    emulating visits already scheduled by the visitors.

    Args:
        num_nodes (int): Total number of nodes |V|. Index 0 is the depot.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        num_brokers (int): Number of brokers sharing the hidden schedule.
        leg_times (list[list[int]]): Travel time the hidden schedule takes for each trip, in minutes.
        first_legs (list[list[int]]): Travel time the hidden schedule takes for each broker's
            first trip of the day, to each node, in minutes.
        service_times (list[int]): Duration s_i of the visit at each node, in minutes.
        horizon (int): Target length of the working day, in minutes.
        fixed_ratio (float): Share of the properties with a fixed start time.
        window_width (tuple[int, int]): Min and max width of a flexible time window, in minutes.

    Returns:
        dict[str, Any]: The time windows (e_i, l_i) for every node, the fixed visits, and the
            broker who does each visit in the hidden schedule (0 for the depot).
    """
    num_properties = num_nodes - 1

    # 1. Enforcing Reproducibility
    rng = np.random.default_rng([random_seed, TIME_WINDOWS_STREAM])

    # 2. Hidden Reference Schedule
    # A random visiting order split among the brokers in consecutive shares
    reference_order = rng.permutation(np.arange(1, num_nodes))
    broker_shares = np.array_split(reference_order, num_brokers)

    # The day is a target, not a constraint: the models before Case 8 have no working-day
    # limit, so a day too short for the busiest broker's work is extended to fit it
    def leg(broker, previous, node):
        return first_legs[broker - 1][node] if previous is None else leg_times[previous][node]

    workloads = [sum(leg(broker, previous, node) + service_times[node]
                     for previous, node in zip([None, *share[:-1]], share))
                 for broker, share in enumerate(broker_shares, start=1)]
    horizon = max(horizon, max(workloads))

    # Each broker's slack in the day is spread as idle gaps between its visits
    reference_start = [0] * num_nodes
    reference_broker = [0] * num_nodes
    for broker, (share, workload) in enumerate(zip(broker_shares, workloads), start=1):
        slack = horizon - workload
        gaps = rng.random(len(share) + 1)
        idle_before = np.cumsum(gaps / gaps.sum() * slack)[:len(share)]

        # Minutes of travel and visits the broker has done so far, idle gaps aside
        busy = 0
        previous = None
        for position, node in enumerate(share):
            busy += leg(broker, previous, node)
            reference_start[node] = math.floor(busy + idle_before[position])
            reference_broker[node] = broker
            busy += service_times[node]
            previous = node

    # 3. Time Windows
    # The depot (node 0) may be left at any time of the day
    earliest_start = [0] * num_nodes
    latest_start = [horizon] * num_nodes

    num_fixed = round(fixed_ratio * num_properties)
    fixed_visits = sorted(int(node) for node in rng.choice(np.arange(1, num_nodes), size=num_fixed, replace=False))

    for node in range(1, num_nodes):
        if node in fixed_visits:
            # Visit already scheduled by the visitor: e_i = l_i
            earliest_start[node] = reference_start[node]
            latest_start[node] = reference_start[node]
        else:
            # Flexible visit: a window containing the reference start time
            width = int(rng.integers(window_width[0], window_width[1] + 1))
            opening = reference_start[node] - int(rng.integers(0, width + 1))
            earliest_start[node] = max(0, opening)
            latest_start[node] = min(horizon - service_times[node], opening + width)

    return {
        'earliest_start': earliest_start,
        'latest_start': latest_start,
        'fixed_visits': fixed_visits,
        'reference_broker': reference_broker
    }


def _generate_assignments(num_nodes: int, random_seed: int, reference_broker: list[int],
                          assigned_ratio: float) -> list[int]:
    """
    Picks the visits that already have a broker, emulating visits booked with a specific
    broker. Each one goes to the broker who does it in the hidden schedule, which keeps
    the instance feasible.

    Args:
        num_nodes (int): Total number of nodes |V|. Index 0 is the depot.
        random_seed (int): Seed for the PRNG to ensure scientific reproducibility.
        reference_broker (list[int]): Broker of each visit in the hidden schedule.
        assigned_ratio (float): Share of the properties whose visit already has a broker.

    Returns:
        list[int]: The broker assigned to each node, 0 when any broker may do it.
    """
    rng = np.random.default_rng([random_seed, ASSIGNMENTS_STREAM])

    num_assigned = round(assigned_ratio * (num_nodes - 1))
    assigned_visits = rng.choice(np.arange(1, num_nodes), size=num_assigned, replace=False)

    assigned_broker = [0] * num_nodes
    for node in assigned_visits:
        assigned_broker[node] = reference_broker[node]

    return assigned_broker


